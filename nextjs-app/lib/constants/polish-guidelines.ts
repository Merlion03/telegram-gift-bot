/**
 * Функция для проверки, что все рекомендации выполнены
 */
export function validatePolishRecommendations(): {
  passed: number;
  failed: number;
  recommendations: string[];
} {
  const recommendations: string[] = [];
  let passed = 0;
  let failed = 0;

  POLISH_CHECKLIST.forEach((category) => {
    category.items.forEach((item) => {
      // Здесь должна быть реальная проверка
      // Для примера просто добавляем в список
      recommendations.push(`${category.category}: ${item}`);
    });
  });

  return {
    passed,
    failed,
    recommendations,
  };
}
